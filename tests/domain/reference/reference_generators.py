def samples(gen, n=6, seed=20261028):
    r = random.Random(seed)
    out, seen = [], set()
    tries = 0
    while len(out) < n and tries < 200:
        tries += 1
        q, a = gen(r)
        if q in seen:
            continue
        seen.add(q)
        out.append((q, a))
    return out


def _self_test():
    import re
    bad = []
    for lv in LEVELS:
        lid, gen = lv[0], lv[-1]
        r = random.Random(1)
        for _ in range(400):
            q, a = gen(r)
            if "あまり" in a:
                m = re.match(r"(\d+)÷(\d+)＝", q)
                n_, d_ = int(m.group(1)), int(m.group(2))
                qq, mm = map(int, a.split("あまり"))
                if not (qq * d_ + mm == n_ and 0 < mm < d_):
                    bad.append((lid, q, a))
            elif a in ("○", "×"):
                m = re.match(r"(\d+)は(\d+)の倍数？", q)
                n_, k_ = int(m.group(1)), int(m.group(2))
                if (n_ % k_ == 0) != (a == "○"):
                    bad.append((lid, q, a))
            else:
                expr = q.replace("＋", "+").replace("－", "-").replace("×", "*").replace("÷", "/").replace("＝", "")
                if "□" in expr:
                    if "と□で" in q:
                        x, tot = re.match(r"(\d+)と□で(\d+)", q).groups()
                        ok = int(x) + int(a) == int(tot)
                    elif "は10と□" in q:
                        tot = int(re.match(r"(\d+)は10と□", q).group(1))
                        ok = 10 + int(a) == tot
                    else:
                        lhs, rhs = expr.split("=") if "=" in expr else (None, None)
                        e = q.replace("＝", "==").replace("□", a).replace("＋", "+").replace("－", "-").replace("×", "*")
                        ok = eval(e)
                    if not ok:
                        bad.append((lid, q, a))
                elif "の半分" in q:
                    if int(q.split("の半分")[0]) != 2 * int(a):
                        bad.append((lid, q, a))
                else:
                    v = eval(expr)
                    if abs(v - int(a)) > 1e-9 or int(a) < 0:
                        bad.append((lid, q, a))
    return bad


